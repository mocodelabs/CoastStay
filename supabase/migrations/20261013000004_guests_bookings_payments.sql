-- ---------------------------------------------------------------------------
-- Bookings
-- ---------------------------------------------------------------------------
create table public.bookings (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations (id) on delete cascade,
  property_id uuid not null,
  unit_id uuid not null,
  guest_id uuid not null,
  -- generated by trigger when left empty, e.g. CS-2610-K7XQP
  booking_reference text not null default '',
  booking_source public.booking_source not null default 'direct',
  external_reference text check (external_reference is null or length(external_reference) <= 100),
  check_in_date date not null,
  check_out_date date not null,
  adults smallint not null default 1 check (adults between 1 and 100),
  children smallint not null default 0 check (children between 0 and 100),
  infants smallint not null default 0 check (infants between 0 and 20),
  nightly_rate numeric(12, 2) not null check (nightly_rate >= 0),
  nights integer generated always as (check_out_date - check_in_date) stored,
  accommodation_amount numeric(12, 2) generated always as (nightly_rate * (check_out_date - check_in_date)) stored,
  cleaning_fee numeric(12, 2) not null default 0 check (cleaning_fee >= 0),
  additional_fees numeric(12, 2) not null default 0 check (additional_fees >= 0),
  discount_amount numeric(12, 2) not null default 0 check (discount_amount >= 0),
  total_amount numeric(12, 2) generated always as (
    nightly_rate * (check_out_date - check_in_date) + cleaning_fee + additional_fees - discount_amount
  ) stored,
  currency char(3) not null default 'KES',
  -- Maintained by app.recompute_booking_financials(); never written directly by clients.
  amount_paid numeric(12, 2) not null default 0,
  amount_refunded numeric(12, 2) not null default 0,
  -- Net non-cash adjustments: debits (charges to guest) minus credits.
  adjustment_total numeric(12, 2) not null default 0,
  -- Amount the business keeps when a booking is cancelled (0 = full refund owed).
  cancellation_fee numeric(12, 2) not null default 0 check (cancellation_fee >= 0),
  balance_due numeric(12, 2) generated always as (
    (case when status = 'cancelled' then cancellation_fee
          else nightly_rate * (check_out_date - check_in_date) + cleaning_fee + additional_fees - discount_amount end)
    - (amount_paid - amount_refunded) + adjustment_total
  ) stored,
  status public.booking_status not null default 'confirmed',
  internal_notes text check (internal_notes is null or length(internal_notes) <= 5000),
  guest_requests text check (guest_requests is null or length(guest_requests) <= 2000),
  cancellation_reason text check (cancellation_reason is null or length(cancellation_reason) <= 1000),
  confirmed_at timestamptz,
  checked_in_at timestamptz,
  checked_out_at timestamptz,
  cancelled_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (organization_id, property_id) references public.properties (organization_id, id),
  foreign key (property_id, unit_id) references public.property_units (property_id, id),
  foreign key (organization_id, guest_id) references public.guests (organization_id, id),
  unique (organization_id, id),
  unique (organization_id, booking_reference),
  check (check_out_date > check_in_date),
  check (check_out_date - check_in_date <= 365),
  check (nightly_rate * (check_out_date - check_in_date) + cleaning_fee + additional_fees - discount_amount >= 0),
  check (currency ~ '^[A-Z]{3}$')
);
create index bookings_org_dates_idx on public.bookings (organization_id, check_in_date, check_out_date);
create index bookings_org_status_idx on public.bookings (organization_id, status);
create index bookings_property_idx on public.bookings (property_id, check_in_date);
create index bookings_unit_idx on public.bookings (unit_id, check_in_date);
create index bookings_guest_idx on public.bookings (guest_id);
create index bookings_checkout_idx on public.bookings (organization_id, check_out_date);
create unique index bookings_external_ref_idx on public.bookings (organization_id, booking_source, external_reference)
  where external_reference is not null and status not in ('cancelled');
alter table public.unit_occupancy
