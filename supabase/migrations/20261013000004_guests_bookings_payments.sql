-- ---------------------------------------------------------------------------
-- Guest visibility helper
-- ---------------------------------------------------------------------------
create or replace function app.guest_in_my_properties(org uuid, guest uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.bookings b
    where b.organization_id = org
      and b.guest_id = guest
      and app.can_access_property(org, b.property_id)
  );
$$;

