-- ---------------------------------------------------------------------------
-- Guests
-- ---------------------------------------------------------------------------
create table public.guests (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations (id) on delete cascade,
  full_name text not null check (length(trim(full_name)) between 2 and 120),
  email extensions.citext check (email is null or email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  -- stored in E.164 where it could be normalized, e.g. +254712345678
  phone text check (phone is null or phone ~ '^\+?[0-9]{7,15}$'),
  country text check (country is null or length(country) <= 60),
  preferences text check (preferences is null or length(preferences) <= 2000),
  notes text check (notes is null or length(notes) <= 5000),
  anonymized_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, id)
);
