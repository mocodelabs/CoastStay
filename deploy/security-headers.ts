/**
 * Single source of truth for the HTTP security headers the static frontend is served with.
 *
 * - `vite preview` applies them (with the local Supabase origin) so the production build can be
 *   checked against the real policy before deploying.
 * - `npm run hosting:config` writes them into `vercel.json` and `public/_headers`
 *   (Netlify / Cloudflare Pages). A unit test fails if those files drift from this module.
 *
 * Plain erasable TypeScript so Node can run it directly (type stripping).
 */

/** Hosted Supabase projects. Replace with your custom domain if you use one (docs/DEPLOYMENT.md). */
export const HOSTED_SUPABASE_ORIGINS = ['https://*.supabase.co', 'wss://*.supabase.co']

export function contentSecurityPolicy(supabaseOrigins: string[] = HOSTED_SUPABASE_ORIGINS): string {
  const https = supabaseOrigins.filter((o) => !o.startsWith('ws'))
  const directives: Array<[string, string[]]> = [
    ['default-src', ["'self'"]],
    ['script-src', ["'self'"]],
    // Toast and Radix components inject small <style> blocks at runtime.
    ['style-src', ["'self'", "'unsafe-inline'"]],
    // Property/expense photos are signed Supabase Storage URLs; previews use blob:/data:.
    ['img-src', ["'self'", 'data:', 'blob:', ...https]],
    ['font-src', ["'self'", 'data:']],
    ['connect-src', ["'self'", ...supabaseOrigins]],
    ['manifest-src', ["'self'"]],
    ['worker-src', ["'self'", 'blob:']],
    ['object-src', ["'none'"]],
    ['base-uri', ["'self'"]],
    ['form-action', ["'self'"]],
    ['frame-ancestors', ["'none'"]],
  ]
  return directives.map(([name, values]) => `${name} ${values.join(' ')}`).join('; ')
}

/** Headers for every response. HSTS is only meaningful over https; hosts ignore it on http. */
export function securityHeaders(supabaseOrigins?: string[]): Record<string, string> {
  return {
    'Content-Security-Policy': contentSecurityPolicy(supabaseOrigins),
    'Strict-Transport-Security': 'max-age=63072000; includeSubDomains',
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
  }
}

/** Hashed build output never changes; index.html must always be revalidated so deploys take effect. */
export const IMMUTABLE_ASSETS = 'public, max-age=31536000, immutable'
export const NO_CACHE = 'no-cache'

export function vercelConfig() {
  return {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    // SPA: every route that is not a file is served by index.html.
    rewrites: [{ source: '/((?!assets/).*)', destination: '/index.html' }],
    headers: [
      { source: '/(.*)', headers: Object.entries(securityHeaders()).map(([key, value]) => ({ key, value })) },
      { source: '/assets/(.*)', headers: [{ key: 'Cache-Control', value: IMMUTABLE_ASSETS }] },
      { source: '/index.html', headers: [{ key: 'Cache-Control', value: NO_CACHE }] },
    ],
  }
}

/** Netlify / Cloudflare Pages `_headers` file. */
export function headersFile(): string {
  const block = (path: string, headers: Record<string, string>) =>
    [path, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join('\n')
  return (
    [
      '# Generated by `npm run hosting:config` from deploy/security-headers.ts — do not edit by hand.',
      block('/*', securityHeaders()),
      block('/assets/*', { 'Cache-Control': IMMUTABLE_ASSETS }),
      block('/index.html', { 'Cache-Control': NO_CACHE }),
    ].join('\n\n') + '\n'
  )
}
