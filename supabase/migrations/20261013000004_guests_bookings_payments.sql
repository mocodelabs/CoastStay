-- Statuses whose dates are reserved in unit_occupancy.
create or replace function app.booking_blocks_dates(s public.booking_status)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select s in ('pending', 'confirmed', 'checked_in');
$$;

create or replace function app.valid_booking_transition(old_s public.booking_status, new_s public.booking_status)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select old_s = new_s or case old_s
    when 'inquiry' then new_s in ('pending', 'confirmed', 'cancelled')
    when 'pending' then new_s in ('confirmed', 'cancelled')
    when 'confirmed' then new_s in ('pending', 'checked_in', 'cancelled', 'no_show')
    when 'checked_in' then new_s in ('checked_out')
    else false
  end;
$$;

create or replace function app.bookings_before_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  org_currency char(3);
  org_tz text;
  prefix text;
  capacity integer;
  unit_status public.unit_status;
  prop_status public.property_status;
  candidate text;
  attempts integer := 0;
  recomputing boolean := coalesce(current_setting('coaststay.recompute', true), '') = 'on';
begin
  select o.currency, o.timezone, s.booking_reference_prefix
    into org_currency, org_tz, prefix
  from public.organizations o
  left join public.organization_settings s on s.organization_id = o.id
  where o.id = new.organization_id;

  if tg_op = 'INSERT' then
    new.currency := org_currency;
    new.amount_paid := 0;
    new.amount_refunded := 0;
    new.adjustment_total := 0;
    if new.booking_reference is null or new.booking_reference = '' then
      loop
        -- e.g. CS-2610-K7XQP (unambiguous alphabet: no 0/O/1/I)
        candidate := coalesce(prefix, 'CS') || '-' || to_char(now() at time zone org_tz, 'YYMM') || '-'
          || (select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', 1 + floor(random() * 32)::int, 1), '')
              from generate_series(1, 5));
        exit when not exists (
          select 1 from public.bookings b
          where b.organization_id = new.organization_id and b.booking_reference = candidate
        );
        attempts := attempts + 1;
        if attempts > 20 then
          raise exception 'Could not generate a booking reference.';
        end if;
      end loop;
      new.booking_reference := candidate;
    end if;
    if new.status = 'confirmed' then new.confirmed_at := now(); end if;
    if new.status in ('checked_in', 'checked_out', 'cancelled', 'no_show') then
      raise exception 'New bookings must start as an inquiry, pending or confirmed.' using errcode = '23514';
    end if;
  else
    if new.organization_id <> old.organization_id then
      raise exception 'A booking cannot be moved to another business.' using errcode = '42501';
    end if;
    if new.booking_reference <> old.booking_reference or new.created_by is distinct from old.created_by
       or new.currency <> old.currency then
      raise exception 'Booking reference, currency and creator cannot be changed.' using errcode = '42501';
    end if;
    if not recomputing and (new.amount_paid <> old.amount_paid or new.amount_refunded <> old.amount_refunded
        or new.adjustment_total <> old.adjustment_total) then
      raise exception 'Payment totals are calculated from recorded transactions and cannot be edited.'
        using errcode = '42501';
    end if;
    if not app.valid_booking_transition(old.status, new.status) then
      raise exception 'A booking cannot move from % to %.', old.status, new.status
        using errcode = '23514', hint = 'invalid_transition';
    end if;
    -- Stays that are finished or cancelled keep their commercial terms.
    if old.status in ('checked_out', 'cancelled', 'no_show') and (
         new.check_in_date <> old.check_in_date or new.check_out_date <> old.check_out_date
         or new.unit_id <> old.unit_id or new.property_id <> old.property_id
         or new.nightly_rate <> old.nightly_rate or new.cleaning_fee <> old.cleaning_fee
         or new.additional_fees <> old.additional_fees or new.discount_amount <> old.discount_amount
         or new.cancellation_fee <> old.cancellation_fee or new.guest_id <> old.guest_id) then
      raise exception 'Dates, unit, guest and pricing of a % booking are locked.', old.status
        using errcode = '23514', hint = 'booking_locked';
    end if;
    if new.status <> old.status then
      case new.status
        when 'confirmed' then new.confirmed_at := coalesce(new.confirmed_at, now());
        when 'checked_in' then new.checked_in_at := now();
        when 'checked_out' then new.checked_out_at := now();
        when 'cancelled' then new.cancelled_at := now();
        else null;
      end case;
    end if;
  end if;

  if new.status = 'cancelled' then
    if new.cancellation_fee > new.nightly_rate * (new.check_out_date - new.check_in_date)
        + new.cleaning_fee + new.additional_fees - new.discount_amount then
      raise exception 'The cancellation fee cannot exceed the booking total.' using errcode = '23514';
    end if;
  elsif new.cancellation_fee <> 0 then
    new.cancellation_fee := 0;
  end if;

  -- Capacity and active-unit checks whenever the stay itself is (re)defined.
  if tg_op = 'INSERT' or new.unit_id <> old.unit_id or new.adults <> old.adults or new.children <> old.children
     or new.check_in_date <> old.check_in_date or new.check_out_date <> old.check_out_date then
    select coalesce(u.max_guests, p.max_guests), u.status, p.status
      into capacity, unit_status, prop_status
    from public.property_units u
    join public.properties p on p.id = u.property_id
    where u.id = new.unit_id and u.property_id = new.property_id;

    if capacity is null then
      raise exception 'The selected unit does not belong to the selected property.' using errcode = '23503';
    end if;
    if new.adults + new.children > capacity then
      raise exception 'This unit sleeps at most % guests (infants excluded).', capacity
        using errcode = '23514', hint = 'capacity_exceeded';
    end if;
    if app.booking_blocks_dates(new.status) and (unit_status <> 'active' or prop_status <> 'active') then
      raise exception 'This property or unit is inactive and cannot take reservations.' using errcode = '23514';
    end if;
  end if;

  return new;
end;
$$;

create trigger bookings_before_write
  before insert or update on public.bookings
  for each row execute function app.bookings_before_write();

create or replace function app.sync_booking_occupancy()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if app.booking_blocks_dates(new.status) then
    insert into public.unit_occupancy (organization_id, unit_id, during, source_type, booking_id)
    values (new.organization_id, new.unit_id, daterange(new.check_in_date, new.check_out_date, '[)'), 'booking', new.id)
    on conflict (booking_id) do update
      set unit_id = excluded.unit_id, during = excluded.during;
  else
    delete from public.unit_occupancy where booking_id = new.id;
  end if;
  return null;
exception
  when exclusion_violation then
    raise exception 'These dates overlap an existing reservation or block for this unit.'
      using errcode = '23P01', hint = 'unit_unavailable';
end;
$$;

create trigger bookings_occupancy
  after insert or update of status, unit_id, check_in_date, check_out_date on public.bookings
  for each row execute function app.sync_booking_occupancy();

