create table public.booking_payments (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations (id) on delete cascade,
  booking_id uuid not null,
  property_id uuid,
  amount numeric(12, 2) not null check (amount > 0),
  currency char(3) not null default 'KES',
  payment_method public.payment_method not null,
  transaction_reference text check (transaction_reference is null or length(transaction_reference) between 3 and 60),
  payment_date date not null,
  payment_type public.payment_type not null,
  status public.payment_status not null default 'recorded',
  reverses_payment_id uuid unique references public.booking_payments (id),
  notes text check (notes is null or length(notes) <= 2000),
  verified_at timestamptz,
  verification_source text,
  recorded_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (organization_id, booking_id) references public.bookings (organization_id, id),
  check ((payment_type = 'reversal') = (reverses_payment_id is not null)),
  check ((status = 'verified') = (verified_at is not null))
);
create index booking_payments_booking_idx on public.booking_payments (booking_id);
create index booking_payments_org_date_idx on public.booking_payments (organization_id, payment_date);
create index booking_payments_property_date_idx on public.booking_payments (property_id, payment_date);
