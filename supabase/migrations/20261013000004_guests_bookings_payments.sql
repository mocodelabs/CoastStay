-- Recalculates the maintained totals on a booking from its ledger.
create or replace function app.recompute_booking_financials(target uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_paid numeric(12, 2);
  v_refunded numeric(12, 2);
  v_adjust numeric(12, 2);
begin
  with eff as (
    select
      case when p.payment_type = 'reversal' then o.payment_type else p.payment_type end as kind,
      case when p.payment_type = 'reversal' then -p.amount else p.amount end as signed_amount
    from public.booking_payments p
    left join public.booking_payments o on o.id = p.reverses_payment_id
    where p.booking_id = target
      and app.payment_is_successful(p.status)
  )
  select
    coalesce(sum(signed_amount) filter (where kind in ('deposit', 'balance', 'payment')), 0),
    coalesce(sum(signed_amount) filter (where kind = 'refund'), 0),
    coalesce(sum(signed_amount) filter (where kind = 'adjustment_debit'), 0)
      - coalesce(sum(signed_amount) filter (where kind = 'adjustment_credit'), 0)
  into v_paid, v_refunded, v_adjust
  from eff;

  perform set_config('coaststay.recompute', 'on', true);
  update public.bookings
    set amount_paid = v_paid, amount_refunded = v_refunded, adjustment_total = v_adjust
    where id = target
      and (amount_paid, amount_refunded, adjustment_total) is distinct from (v_paid, v_refunded, v_adjust);
  perform set_config('coaststay.recompute', 'off', true);
end;
$$;

create or replace function app.booking_payments_before_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  b record;
  orig record;
  enabled public.payment_method[];
  uid uuid := (select auth.uid());
begin
  if tg_op = 'INSERT' then
    select bk.property_id, bk.currency, bk.status, bk.amount_paid, bk.amount_refunded
      into b
    from public.bookings bk
    where bk.id = new.booking_id and bk.organization_id = new.organization_id
    for update;

    new.property_id := b.property_id;
    new.currency := b.currency;
    new.transaction_reference := nullif(upper(trim(new.transaction_reference)), '');

    -- Only a trusted integration (service role, no end-user JWT) may create verified entries.
    if uid is not null and new.status not in ('recorded', 'pending') then
      raise exception 'Manually entered transactions are saved as recorded or pending.' using errcode = '42501';
    end if;
    if new.status <> 'verified' then
      new.verified_at := null;
      new.verification_source := null;
    end if;

    if new.payment_type = 'reversal' then
      select * into orig from public.booking_payments where id = new.reverses_payment_id;
      if orig.id is null or orig.booking_id <> new.booking_id then
        raise exception 'The transaction being reversed does not belong to this booking.' using errcode = '23503';
      end if;
      if orig.payment_type = 'reversal' then
        raise exception 'A reversal cannot itself be reversed.' using errcode = '23514';
      end if;
      if not app.payment_is_successful(orig.status) then
        raise exception 'Only recorded or verified transactions can be reversed.' using errcode = '23514';
      end if;
      new.amount := orig.amount;
      new.payment_method := orig.payment_method;
      new.status := 'recorded';
      if orig.payment_type in ('deposit', 'balance', 'payment')
         and b.amount_paid - orig.amount < b.amount_refunded then
        raise exception 'Reverse the related refund first: refunds would exceed payments received.'
          using errcode = '23514';
      end if;
    else
      select s.enabled_payment_methods into enabled
      from public.organization_settings s where s.organization_id = new.organization_id;
      if enabled is not null and not (new.payment_method = any (enabled)) then
        raise exception 'This payment method is disabled in settings.' using errcode = '23514';
      end if;
      if new.payment_type = 'refund' and app.payment_is_successful(new.status)
         and new.amount > b.amount_paid - b.amount_refunded then
        raise exception 'A refund cannot exceed the net amount received (% %).',
          b.currency, to_char(b.amount_paid - b.amount_refunded, 'FM999,999,999,990.00')
          using errcode = '23514', hint = 'refund_exceeds_received';
      end if;
    end if;
    if new.payment_date > (now() at time zone (
         select o.timezone from public.organizations o where o.id = new.organization_id))::date then
      raise exception 'Payment date cannot be in the future.' using errcode = '23514';
    end if;
    return new;
  end if;

  -- UPDATE: finalized transactions are immutable apart from notes; status only moves forward.
  if new.organization_id <> old.organization_id or new.booking_id <> old.booking_id
     or new.amount <> old.amount or new.payment_method <> old.payment_method
     or new.payment_type <> old.payment_type or new.payment_date <> old.payment_date
     or new.transaction_reference is distinct from old.transaction_reference
     or new.reverses_payment_id is distinct from old.reverses_payment_id
     or new.recorded_by is distinct from old.recorded_by
     or new.property_id is distinct from old.property_id then
    raise exception 'Recorded transactions cannot be edited. Record a reversal or adjustment instead.'
      using errcode = '42501', hint = 'ledger_immutable';
  end if;
  if new.status <> old.status then
    if not (
      (old.status = 'pending' and new.status in ('recorded', 'failed'))
      or (old.status in ('pending', 'recorded') and new.status = 'verified' and uid is null)
    ) then
      raise exception 'A transaction cannot move from % to %.', old.status, new.status using errcode = '42501';
    end if;
  end if;
  return new;
end;
$$;

create trigger booking_payments_before_write
  before insert or update on public.booking_payments
  for each row execute function app.booking_payments_before_write();

